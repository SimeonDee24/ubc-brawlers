#!/usr/bin/env python3
"""Turn the 2D joints baked out of Blender (baked2d.json, see export.py) into
characters/simeon-anims.js: one integer pose per frame for the engine, so
hitboxes and hurtboxes follow the 3D animation exactly and stay deterministic.

  python3 tools/blender/bake-to-js.py path/to/baked2d.json > characters/simeon-anims.js
"""
import json, math, sys

FX = 256
HIP_Y = 22                 # skeleton.hipY in characters/simeon.js
FOOT_REST = 14.6           # degrees the ankle->toe line points down at rest
FACES = ['neutral', 'smile', 'yell', 'hurt', 'focus']

def ang(a, b):
    """angle of b - a: 0 = straight down, positive = toward the front (x+)"""
    return math.degrees(math.atan2(b[0] - a[0], b[1] - a[1]))

def wrap(d):
    while d > 180: d -= 360
    while d < -180: d += 360
    return d

def row(j):
    hip, neck, top = j['hip'], j['neck'], j['headTop']
    torso = math.degrees(math.atan2(neck[0] - hip[0], hip[1] - neck[1]))
    head = math.degrees(math.atan2(top[0] - neck[0], neck[1] - top[1]))
    afu = ang(j['shF'], j['elF']); afl = wrap(ang(j['elF'], j['wrF']) - afu)
    abu = ang(j['shB'], j['elB']); abl = wrap(ang(j['elB'], j['wrB']) - abu)
    lfu = ang(j['hipF'], j['kneeF']); lfl = wrap(ang(j['kneeF'], j['ankF']) - lfu)
    lbu = ang(j['hipB'], j['kneeB']); lbl = wrap(ang(j['kneeB'], j['ankB']) - lbu)
    ff = wrap(math.degrees(math.atan2(j['toeF'][1] - j['ankF'][1], j['toeF'][0] - j['ankF'][0])) - FOOT_REST)
    fb = wrap(math.degrees(math.atan2(j['toeB'][1] - j['ankB'][1], j['toeB'][0] - j['ankB'][0])) - FOOT_REST)
    r = [round(hip[0]*FX), round((hip[1] + HIP_Y)*FX)] + [round(v) for v in (torso, head, afu, afl, abu, abl, lfu, lfl, lbu, lbl, ff, fb)]
    r += [1 if j['handF'] == 'fist' else 0, 1 if j['handB'] == 'fist' else 0, FACES.index(j.get('face', 'neutral'))]
    if 'wF' in j:
        r += [[round(j['wF'][0]*FX), round(j['wF'][1]*FX)], [round(j['wM'][0]*FX), round(j['wM'][1]*FX)]]
    return r

def main():
    data = json.load(open(sys.argv[1]))
    out = ['// GENERATED by tools/blender/bake-to-js.py from the Blender bake: do not edit by hand.',
           '// Simeon\'s animations, one integer pose per frame, matching assets/models/simeon.glb.',
           "import { bakedAnim } from '../engine/skeleton.js';",
           '',
           'const F = ' + json.dumps(FACES) + ';',
           'export const SIMEON_ANIMS = {']
    for name in sorted(data):
        a = data[name]
        rows = [row(j) for j in a['frames']]
        body = ',\n    '.join(json.dumps(r, separators=(',', ':')) for r in rows)
        out.append(f"  {name}: bakedAnim({'true' if a['loop'] else 'false'}, [\n    {body},\n  ], F),")
    out.append('};')
    print('\n'.join(out))

main()
